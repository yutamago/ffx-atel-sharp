using System.Globalization;
using System.Text;
using Ffx.Atel.Bytecode.Script;
using Ffx.Atel.Bytecode.Vbf;

namespace Ffx.Atel.Bytecode.Analysis;

/// <summary>One script of the corpus, parsed, with every worker's flow.</summary>
public sealed class SurveyScript {
    public required string Path { get; init; }
    public required string Kind { get; init; }
    public required ScriptBlock Block { get; init; }
    public required WorkerFlow[] Flows { get; init; }

    /// <summary>The file name without folder and extension (<c>bjyt0400</c>, <c>m001</c>).</summary>
    public string Name => System.IO.Path.GetFileNameWithoutExtension(Path);
}

/// <summary>
///     Phase 0 of docs/plan.md: measures what the decompiler and compiler have to reproduce, over every
///     shipped script. <see cref="Run"/> writes a Markdown report; docs/corpus.md is written from it.
/// </summary>
public sealed partial class Survey {
    private readonly List<SurveyScript> _scripts;
    private readonly NativeSignatures _natives;
    private readonly StringBuilder _out = new();

    /// <summary>Story progress values, by value: the scripts that store each.</summary>
    public SortedDictionary<int, SortedSet<string>> StoryWrites { get; } = [];

    public IReadOnlyList<SurveyScript> Scripts => _scripts;

    public Survey(IEnumerable<SurveyScript> scripts, NativeSignatures natives) {
        _scripts = [.. scripts];
        _natives = natives;
    }

    /// <summary>The kind of script an archive path holds: <c>monster</c>, <c>battle</c> or <c>event</c>.</summary>
    public static string KindOf(string path) =>
        path.StartsWith(GameData.MonsterPrefix, StringComparison.Ordinal) ? "monster"
        : path.StartsWith(GameData.BattlePrefix, StringComparison.Ordinal) ? "battle"
        : "event";

    /// <summary>Reads and analyses every script of the archive (<see cref="GameData.AllScriptPaths"/>).</summary>
    public static Survey Load(VbfArchive archive, NativeSignatures natives) {
        List<string> paths = GameData.AllScriptPaths(archive);
        SurveyScript[] scripts = new SurveyScript[paths.Count];
        byte[][] files = [.. paths.Select(archive.Read)];
        Parallel.For(0, paths.Count, k => {
            ScriptBlock block = ScriptFile.Parse(files[k]).Script;
            scripts[k] = new SurveyScript {
                Path = paths[k],
                Kind = KindOf(paths[k]),
                Block = block,
                Flows = [.. Enumerable.Range(0, block.Workers.Count).Select(w => new WorkerFlow(block, w, natives))],
            };
        });
        return new Survey(scripts, natives);
    }

    /// <summary>Runs every measurement; returns the report.</summary>
    public string Run() {
        _out.Clear();
        Line("# Corpus survey");
        Line();
        Line($"Generated by `atel survey` over {_scripts.Count} scripts ({Count("monster")} monster, {Count("event")} event, {Count("battle")} battle), "
             + $"{_scripts.Sum(s => s.Block.Workers.Count)} workers, {_scripts.Sum(s => s.Flows.Sum(f => (long)f.Code.Count))} instructions.");
        MeasureStack();
        MeasureJumps();
        MeasureSwitches();
        MeasureLoops();
        MeasureEncoding();
        MeasurePools();
        MeasureWorkers();
        MeasureRequests();
        MeasureDuplicates();
        MeasureStory();
        MeasureEntryData();
        return _out.ToString();
    }

    private int Count(string kind) => _scripts.Count(s => s.Kind == kind);

    // ----- Output helpers ------------------------------------------------------------------------------------

    private void Line(string text = "") => _out.Append(text).Append('\n');

    private void Section(string title) {
        Line();
        Line($"## {title}");
        Line();
    }

    private void Sub(string title) {
        Line();
        Line($"### {title}");
        Line();
    }

    private void Table(string[] header, IEnumerable<IEnumerable<object?>> rows) {
        List<IEnumerable<object?>> list = [.. rows];
        if (list.Count == 0) {
            Line("(none)");
            return;
        }
        Line("| " + string.Join(" | ", header) + " |");
        Line("|" + string.Concat(header.Select(_ => "---|")));
        foreach (IEnumerable<object?> r in list) Line("| " + string.Join(" | ", r.Select(Cell)) + " |");
    }

    /// <summary>"`a` 3, `b` 2" from counts, most first; "none" when empty.</summary>
    private static string Counts<TKey>(Dictionary<TKey, long> d, int take = int.MaxValue, bool code = true) where TKey : notnull =>
        d.Count == 0 ? "none" : string.Join(", ", d.OrderByDescending(k => k.Value).Take(take).Select(k => code ? $"`{k.Key}` {N(k.Value)}" : $"{k.Key} {N(k.Value)}"));

    private static string Cell(object? v) => v switch {
        null => "",
        int i => N(i),
        long l => N(l),
        double d => d.ToString("0.##", CultureInfo.InvariantCulture),
        _ => Convert.ToString(v, CultureInfo.InvariantCulture) ?? "",
    };

    /// <summary>A number with thousands separators.</summary>
    private static string N(long v) => v.ToString("#,0", CultureInfo.InvariantCulture);

    private static string Pct(long part, long whole) => whole == 0 ? "-" : (100.0 * part / whole).ToString("0.##", CultureInfo.InvariantCulture) + " %";

    /// <summary>A short snippet: instructions <paramref name="from"/> to <paramref name="to"/> of a worker, as assembly.</summary>
    private string Snippet(SurveyScript s, WorkerFlow f, int from, int to, string? note = null) {
        StringBuilder sb = new();
        sb.Append("```\n");
        sb.Append(CultureInfo.InvariantCulture, $"; {s.Name}, worker {f.WorkerIndex}{(note is null ? "" : ", " + note)}\n");
        from = Math.Max(from, 0);
        to = Math.Min(to, f.Code.Count - 1);
        for (int i = from; i <= to; i++) {
            foreach (int e in f.EntriesHere[i]) sb.Append(CultureInfo.InvariantCulture, $"e{e}:\n");
            foreach (int l in f.LabelsHere[i]) sb.Append(CultureInfo.InvariantCulture, $"l{l}:\n");
            string text = Assembly.Render(s.Block, f.WorkerIndex, f.Code[i]);
            if (f.Code[i].Code is Opcodes.Func or Opcodes.FuncFacc && _natives[f.Code[i].Operand!.Value] is NativeSignature sig) {
                text = $"{text,-24} ; {sig.Name}";
            }
            string depth = f.Depth[i] >= 0 ? $"[{f.Depth[i]}]" : "[-]";
            sb.Append(CultureInfo.InvariantCulture, $"    {depth,-5}{text}\n");
        }
        sb.Append("```");
        return sb.ToString();
    }

    private IEnumerable<(SurveyScript Script, WorkerFlow Flow)> AllFlows() =>
        _scripts.SelectMany(s => s.Flows.Select(f => (s, f)));
}
