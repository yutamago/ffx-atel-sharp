using System;

namespace Ffx.Atel;

/// <summary>Marks a method as a native function of the game: the compiler emits <c>func id</c> for a call.</summary>
/// <param name="id">The native's ID: group in bits 12–15, index below.</param>
[AttributeUsage(AttributeTargets.Method | AttributeTargets.Property, Inherited = false)]
public sealed class NativeAttribute(int id) : Attribute {
    public int Id { get; } = id;

    /// <summary>The native has a poll handler: the call may span frames until it reports done.</summary>
    public bool Polls { get; init; }
}

/// <summary>
///     Marks a member of the object-oriented surface (<c>Pos</c>, <c>Turn.Start</c>, <c>Wait.Frames</c>;
///     docs/language.md, "Members") as native <paramref name="id"/>: the compiler lowers a call of the method, or a
///     read or write of the property (on the accessor), onto <c>func id</c> with the same arguments, so the
///     bytecode is the native call's. Generated by <c>tools/gen-members.cs</c> from <c>data/native-members.json</c>.
/// </summary>
/// <param name="id">The native's ID.</param>
[AttributeUsage(AttributeTargets.Method, AllowMultiple = true, Inherited = false)]
public sealed class NativeMemberAttribute(int id) : Attribute {
    public int Id { get; } = id;

    /// <summary>The native has a poll handler: the call may span frames until it reports done.</summary>
    public bool Polls { get; init; }

    /// <summary>
    ///     The native's first argument is the worker it acts on: this worker (<c>Common.GetWorkerId(-1)</c>) when
    ///     the member is written alone, else the worker written before it (<c>Tidus.Turn.Stop()</c>,
    ///     <c>Workers[n].Turn.Stop()</c>).
    /// </summary>
    public bool Worker { get; init; }

    /// <summary>On a <see cref="Ffx.Vector3"/> getter: the component (<c>X</c>, <c>Y</c>, <c>Z</c>) this native reads.</summary>
    public string? Component { get; init; }
}

/// <summary>Members of the reference assembly only describe the game; they never run on .NET.</summary>
public static class Runtime {
    public static Exception NotRunnable() => new InvalidOperationException("Atel code runs in the game's script interpreter, not on .NET.");
}
