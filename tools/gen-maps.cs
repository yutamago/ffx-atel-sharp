// Writes src/Ffx.Atel.Game/Map.g.cs: the maps (events) by number, the number the map changes take
// (Common.MapChange, Common.MapJump, …: AtelSetEventJump2(map, entrance, …)). The number is the event's index
// in the game's map table event/header/eventid.bin (8-byte entries: offset and length of the event's name;
// initEventList, ffx-rust docs/formats/field.md), checked in game: MapJump(393, 0) runs scene1
// (docs/research/loader.md). Each member is the event's script class (`kami0000` -> `Map.Kami0000`), its
// summary the script's namespace (`Events.Ka_ThunderPlains.Kami0000`). Phase 5 of docs/plan.md.
//
// Nothing from the game is written but the event names (the script file names) and their numbers.
//
// usage: FFX_GAME_DIR=<game> dotnet run tools/gen-maps.cs

#:project ../src/Ffx.Atel.Decompiler
#:property PublishAot=false

using System.Buffers.Binary;
using System.Globalization;
using System.Runtime.CompilerServices;
using System.Text;
using Ffx.Atel.Bytecode;
using Ffx.Atel.Decompiler;

if (GameData.GameDir() is not string gameDir) {
    Console.Error.WriteLine("usage: FFX_GAME_DIR=<game> dotnet run tools/gen-maps.cs");
    return 1;
}
string root = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(ThisFile())!, ".."));
using var archive = GameData.OpenArchive(gameDir);
string tablePath = archive.Entries.Select(e => e.Path).Single(p => p.EndsWith("/event/header/eventid.bin", StringComparison.Ordinal));
byte[] table = archive.Read(tablePath);

int count = BinaryPrimitives.ReadInt32LittleEndian(table) / 8;
StringBuilder cs = new();
cs.Append("""
    // SPDX-License-Identifier: MIT
    // <auto-generated> by tools/gen-maps.cs from the game's map table (event/header/eventid.bin): do not edit. </auto-generated>

    namespace Ffx;

    /// <summary>
    ///     A map (an event), by number: <c>Common.MapJump(Map.Kami0000, 0)</c>. The number is the event's
    ///     index in the game's map table (<c>event/header/eventid.bin</c>), which the map changes take
    ///     (<c>AtelSetEventJump2(map, entrance, …)</c>); each member is named after the event's script, and its
    ///     summary gives the script's namespace.
    /// </summary>
    public enum Map
    {

    """);
HashSet<string> used = new(StringComparer.Ordinal);
int named = 0, withScript = 0;
for (int i = 0; i < count; i++) {
    int offset = BinaryPrimitives.ReadInt32LittleEndian(table.AsSpan(8 * i));
    int length = BinaryPrimitives.ReadInt32LittleEndian(table.AsSpan(8 * i + 4));
    string name = Encoding.ASCII.GetString(table, offset, length).TrimEnd('\0');
    if (name.Length == 0) continue;
    string member = SourceNames.Identifier(name);
    if (!used.Add(member)) throw new InvalidOperationException($"eventid.bin: {name} twice");
    string? path = GameData.Find(archive, ScriptCategory.Event, name);
    string where = path is null ? "no script in the archive" : $"<c>{SourceNames.ForPath(path).Namespace}</c>";
    if (path is not null) withScript++;
    cs.Append(CultureInfo.InvariantCulture, $"    /// <summary><c>{name}</c>: {where}.</summary>\n    {member} = {i},\n");
    named++;
}
cs.Append("}\n");
File.WriteAllText(Path.Combine(root, "src", "Ffx.Atel.Game", "Map.g.cs"), cs.ToString());
Console.WriteLine($"{count} maps in the table, {named} named, {withScript} with a script");
return 0;

static string ThisFile([CallerFilePath] string path = "") => path;
