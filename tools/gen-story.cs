// Writes src/Ffx.Atel.Game/Story.g.cs: a constant per story progress value the shipped scripts store
// (storage 0 offset 0xa00, g_SaveData + 0xbec), from data/story-progress.json (`atel survey --story`).
// docs/plan.md, "Readability" and "Phase 5: typing and naming".
//
//   - The name is `S` + the value zero-padded to five digits (the highest is 11000), so that
//     alphabetical order is progress order, then the scripts that store it: `S01340_Bjyt0400`.
//   - The scripts are the ones outside the developer maps (`test*`, `sample*`), unless only those
//     store the value; the regional and Vita copies of a script (`cn_`, `psv_`, `psvcn_` prefixes)
//     count as the script itself, as does a copy under another prefix (`200thunder_kami0400`). Two scripts give both names, more the first two and `Etc`.
//   - data/story-names.json, when present, renames values by hand: { "1340": "WakkaJoinsParty" }
//     gives `S01340_WakkaJoinsParty`.
//
// usage: dotnet run tools/gen-story.cs

#:property PublishAot=false

using System.Globalization;
using System.Runtime.CompilerServices;
using System.Security;
using System.Text;
using System.Text.Json;

string root = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(ThisFile())!, ".."));
using JsonDocument data = JsonDocument.Parse(File.ReadAllText(Path.Combine(root, "data", "story-progress.json")));
Dictionary<int, string> manual = [];
string manualPath = Path.Combine(root, "data", "story-names.json");
if (File.Exists(manualPath)) {
    using JsonDocument m = JsonDocument.Parse(File.ReadAllText(manualPath));
    foreach (JsonProperty p in m.RootElement.EnumerateObject()) manual[int.Parse(p.Name, CultureInfo.InvariantCulture)] = p.Value.GetString()!;
}

static bool Developer(string s) => s.StartsWith("test", StringComparison.Ordinal) || s.StartsWith("sample", StringComparison.Ordinal);

static string Base(string s) {
    foreach (string prefix in new[] { "psvcn_", "psv_", "cn_" }) {
        if (s.StartsWith(prefix, StringComparison.Ordinal)) return s[prefix.Length..];
    }
    return s;
}

static string Pascal(string s) {
    StringBuilder sb = new();
    foreach (char c in s) sb.Append(char.IsAsciiLetterOrDigit(c) ? c : '_');
    if (sb.Length > 0) sb[0] = char.ToUpperInvariant(sb[0]);
    return sb.ToString();
}

StringBuilder cs = new();
cs.Append("""
    // SPDX-License-Identifier: MIT
    // <auto-generated> by tools/gen-story.cs from data/story-progress.json: do not edit. </auto-generated>

    namespace Ffx;

    /// <summary>
    ///     The story progress values the shipped scripts store in <c>Save.StoryProgress</c> (storage 0
    ///     offset <c>0xa00</c>, <c>g_SaveData + 0xbec</c>; Fahrenheit's <c>story_progress</c>). Each is
    ///     named after the scripts that store it, the value zero-padded so that alphabetical order is
    ///     progress order; hand names come from <c>data/story-names.json</c>.
    /// </summary>
    public static class Story
    {

    """);
int count = 0;
foreach (JsonElement v in data.RootElement.GetProperty("values").EnumerateArray()) {
    int value = v.GetProperty("value").GetInt32();
    List<string> all = [.. v.GetProperty("scripts").EnumerateArray().Select(s => s.GetString()!)];
    List<string> release = [.. all.Where(s => !Developer(s))];
    List<string> names = [.. (release.Count > 0 ? release : all).Select(Base).Distinct().Order(StringComparer.Ordinal)];
    // A copy of another script under a prefix (`200thunder_kami0400` of `kami0400`) counts as that script.
    names = [.. names.Where(n => !names.Any(o => o != n && n.EndsWith("_" + o, StringComparison.Ordinal)))];
    string suffix = manual.TryGetValue(value, out string? hand) ? hand
        : names.Count <= 2 ? string.Join("_", names.Select(Pascal))
        : $"{Pascal(names[0])}_{Pascal(names[1])}_Etc";
    string name = string.Create(CultureInfo.InvariantCulture, $"S{value:D5}_{suffix}");
    cs.Append(CultureInfo.InvariantCulture, $"    /// <summary>Stored by {SecurityElement.Escape(string.Join(", ", all))}.</summary>\n");
    cs.Append(CultureInfo.InvariantCulture, $"    public const int {name} = {value};\n");
    count++;
}
cs.Append("}\n");
File.WriteAllText(Path.Combine(root, "src", "Ffx.Atel.Game", "Story.g.cs"), cs.ToString());
Console.WriteLine($"{count} story values");
return 0;

static string ThisFile([CallerFilePath] string path = "") => path;
